// Web 指纹规则库。
//
// 设计取向：这不是 wappalyzer 的搬运，而是一张【只保留能对接 CVE 情报的条目】的
// 精简表。每条的 Product/Vendor 都按 CPE 命名写死，目的只有一个——命中后能原样
// 拼成 search_vulns(product=..., vendor=..., version=...) 的调用。识别一个没有
// 已知漏洞面的前端库没有意义，识别出「Tomcat 9.0.31」才有。
//
// 每条规则只描述【一种证据】。同一产品可以有多条（Server 头 / Cookie / 正文特征），
// 引擎按 product 去重、取最高置信度并合并证据——多条弱证据加起来仍然是弱证据，
// 不做「三票通过」的加权（那会把「引用了别人 CDN 的 WordPress 图片」判成 WordPress）。
//
// 置信度分层（命中概率，不是危害）：
//   0.95 响应头/生成器里显式自报版本（Server: nginx/1.18.0）
//   0.90 Cookie 名（rememberMe= → Shiro，JSESSIONID 只能判容器不能判产品，故不单列）
//   0.85 特定路径/文件名（/wp-content/、/actuator 错误页）
//   0.80 前端资源版本号（jquery-3.4.1.min.js）
//   0.70 正文关键词（Powered by Discuz）——会被转载/引用污染，故低

import "regexp"

// fpRule 一条指纹证据规则。
//
// On 取值决定在哪个语料上匹配：
//
//	header  响应头（Field 非空时只看该头，否则看「头名: 值」的拼接）
//	cookie  Set-Cookie 的拼接
//	title   <title> 内容
//	body    HTML 正文
//	link    HTML 里所有 src/href/action 属性的拼接
type fpRule struct {
	Name     string // 展示名
	Product  string // CPE product（search_vulns 的 product）
	Vendor   string // CPE vendor（search_vulns 的 vendor，可空）
	Category string // web-server / language / middleware / framework / cms / platform / js-lib
	On       string
	Field    string // On=header 时限定头名
	Re       *regexp.Regexp
	VerRe    *regexp.Regexp // 版本捕获；nil 时用通用版本号兜底
	Conf     float64
	Note     string // 识别依据的人话说明（给证据用）
}

